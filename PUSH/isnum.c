// checks if its a num or no 1 mistake 0 all good
int	isnum(char *a)
{
	if (!a)
		return (1);
	if (*a == '-' || *a == '+')
		a++;
	while(*a)
	{
		if((*a < '0' || *a > '9'))
			return (1);
		a++;
	}
	return (0);
}